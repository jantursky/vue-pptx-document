// Writes src/core/known-props.ts: the props each primitive understands, read from the component
// prop types and the PptxGenJS option types they pass through to. The unknown-prop warning uses
// it. With `--check` it only reports whether the file is current, which a unit test runs.
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import * as prettier from 'prettier'
import ts from 'typescript'

const root = join(import.meta.dirname, '..')
const output = join(root, 'src/core/known-props.ts')

// Node type, then the types whose keys it accepts.
const SOURCES = {
  PRESENTATION: ['T.PresentationProps'],
  MASTER: ['T.MasterProps'],
  SLIDE: ['T.SlideProps'],
  VIEW: ['T.ViewProps'],
  TEXT: ['T.TextProps', 'P.TextPropsOptions'],
  PARAGRAPH: ['T.ParagraphProps', 'P.TextPropsOptions'],
  RUN: ['T.RunProps', 'P.TextPropsOptions'],
  PLACEHOLDER: ['T.PlaceholderProps', 'P.TextPropsOptions', 'P.PlaceholderProps'],
  SHAPE: ['T.ShapeProps', 'P.ShapeProps', 'P.TextPropsOptions'],
  IMAGE: ['T.ImageProps', 'P.ImageProps'],
  TABLE: ['T.TableProps', 'P.TableProps', 'P.TableCellProps'],
  TABLE_ROW: ['T.TableCellProps', 'P.TableCellProps'],
  TABLE_CELL: ['T.TableCellProps', 'P.TableCellProps'],
  CHART: ['T.ChartProps'],
  MEDIA: ['T.MediaProps', 'P.MediaProps'],
}

export const generate = async () => {
  const probe = join(root, 'src/core/__known-props-probe.ts')
  // One alias per source type; its declared properties (not index signatures) are the keys.
  const aliases = Object.entries(SOURCES).flatMap(([type, sources]) =>
    sources.map((source, index) => `export type ${type}__${index} = ${source}`),
  )
  const text = ["import type * as T from '../components/types'", "import type P from 'pptxgenjs'", ...aliases].join(
    '\n',
  )

  const host = ts.createCompilerHost({})
  const readFile = host.readFile.bind(host)
  host.readFile = (file) => (file === probe ? text : readFile(file))
  const fileExists = host.fileExists.bind(host)
  host.fileExists = (file) => file === probe || fileExists(file)
  const program = ts.createProgram(
    [probe],
    {
      strict: true,
      module: ts.ModuleKind.ESNext,
      moduleResolution: ts.ModuleResolutionKind.Bundler,
      skipLibCheck: true,
      noEmit: true,
    },
    host,
  )
  const checker = program.getTypeChecker()
  const file = program.getSourceFile(probe)
  const known = {}
  for (const statement of file.statements) {
    if (!ts.isTypeAliasDeclaration(statement)) continue
    const [type] = statement.name.text.split('__')
    const names = checker.getPropertiesOfType(checker.getTypeAtLocation(statement.name)).map((symbol) => symbol.name)
    known[type] = new Set([...(known[type] ?? []), ...names])
  }
  const lines = Object.entries(known).map(([type, keys]) => `  ${type}: '${[...keys].sort().join(' ')}',`)
  const code = [
    '// Generated by scripts/known-props.js from the prop and PptxGenJS option types. Do not edit.',
    '// Run `node scripts/known-props.js` after changing src/components/types.ts or updating PptxGenJS.',
    'export const KNOWN_PROPS: Record<string, string> = {',
    ...lines,
    '}',
    '',
  ].join('\n')
  // Formatted like the rest of the code, so `prettier --check` and the up-to-date test agree.
  const config = await prettier.resolveConfig(output)
  return prettier.format(code, { ...config, filepath: output })
}

const isMain = process.argv[1] === import.meta.filename
if (isMain) {
  const next = await generate()
  if (process.argv.includes('--check')) {
    const current = readFileSync(output, 'utf8')
    if (current !== next) {
      console.error('src/core/known-props.ts is out of date. Run `node scripts/known-props.js`.')
      process.exit(1)
    }
  } else {
    writeFileSync(output, next)
  }
}
